const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const window = {};
vm.runInNewContext(fs.readFileSync(require.resolve('../js/admin-calendar-core.js'), 'utf8'), { window, Date });
const C = window.AdminCalendarCore;
const at = s => Date.parse(s + '-04:00');
const request = { id:'request:101:r1', source:'agent_request', status:'Approved', date:'2026-10-09', endDate:'2026-10-09', type:'dayoff', allDay:true, time:'', reminder:1440, revision:2 };
assert.equal(C.reminderAt(request, at('2026-10-07T15:00:00')), null);
assert.equal(C.reminderAt(request, at('2026-10-08T08:59:59')), null);
const before = C.reminderAt(request, at('2026-10-08T09:00:00'));
assert.equal(before.reminderLabel, 'Tomorrow: approved time off');
const day = C.reminderAt(request, at('2026-10-09T00:00:00'));
assert.equal(day.reminderLabel, 'Today: approved time off');
assert.notEqual(C.occurrence(day), C.occurrence(before), 'dismissing the day-before reminder cannot dismiss the actual-day reminder');
assert.equal(C.occurrence(day), C.occurrence(C.reminderAt(request, at('2026-10-09T23:59:59'))), 'one reminder per actual day');
assert.equal(C.reminderAt(request, at('2026-10-10T00:00:00')), null);
assert.equal(request.status, 'Approved'); assert.equal(request.date, '2026-10-09');
const multi = { ...request, endDate:'2026-10-11' };
assert.notEqual(C.occurrence(C.reminderAt(multi, at('2026-10-10T08:00:00'))), C.occurrence(C.reminderAt(multi, at('2026-10-11T08:00:00'))));
for (const type of ['late','early','appointment']) assert.equal(C.reminderAt({ ...request,type,time:'15:30',allDay:false },at('2026-10-09T06:00:00')).reminderPhase,'day-2026-10-09');
for (const status of ['Declined','Cancelled']) assert.equal(C.reminderAt({ ...request,status },at('2026-10-09T10:00:00')),null);
const manual = { ...request,source:undefined };
assert.equal(C.reminderAt(manual,at('2026-10-09T10:00:00')),manual,'existing manual-event reminders are unchanged');
console.log('Calendar reminder checks passed: day-before timing, separate daily dismissals, expiry, multi-day requests and existing event behavior.');
