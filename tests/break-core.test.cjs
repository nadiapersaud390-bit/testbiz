const assert = require('node:assert/strict');
const C = require('../js/break-core.js');
const at = t => Date.parse('2026-09-21T' + t + ':00-04:00');
const schedule = {time:'10:00',minutes:10};
const identity = {userId:'1234',name:'Alice',team:'BB'};
assert.equal(C.day(Date.parse('2026-09-22T02:00:00Z')), '2026-09-21');
assert.equal(C.available(null,schedule,'morning',at('09:59')),false);
assert.equal(C.available(null,schedule,'morning',at('10:00')),true);
assert.equal(C.validSchedule({time:'13:00',minutes:10},'morning'),false);
assert.equal(C.validSchedule({time:'10:00',minutes:0},'morning'),false);
assert.equal(C.validSchedule({time:'25:00',minutes:10},'afternoon'),false);
const first = C.begin(null,schedule,'morning',at('10:00'),identity,at('10:00'));
assert.equal(C.dueAt(first.active),at('10:10'));
assert.equal(C.begin(first,schedule,'morning',at('10:01'),identity,at('10:01')),undefined);
assert.equal(C.available(first,{time:'14:00',minutes:10},'afternoon',at('14:00')),false);
assert.equal(C.finish(first,'wrong',at('10:11')),undefined);
const returned = C.finish(first,first.active.id,at('10:11'));
assert.equal(returned.active,null);
assert.equal(returned.days['2026-09-21'].morning.returnedAt,at('10:11'));
assert.equal(C.available(returned,schedule,'morning',at('10:12')),false);
assert.equal(C.available(returned,{time:'14:00',minutes:10},'afternoon',at('14:00')),true);
assert.equal(C.available(returned,schedule,'morning',at('10:00')+86400000),true);
assert.equal(C.available(first,schedule,'morning',at('10:00')+86400000),false);
assert.equal(C.duration(61000),'01:01');
assert.equal(C.duration(-1000),'00:00');
console.log('Break core: 17 assertions passed.');
